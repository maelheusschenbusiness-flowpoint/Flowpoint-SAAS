// ── Protected router — all management endpoints (requires auth) ───────────────
// Mounted after requireAuth in index.ts.

const router = Router();

router.get("/google/connect", (_req: Request, res: Response) => {
  if (!isGoogleConfigured()) {
    res.status(503).json({
      ok: false,
      error: "Google OAuth not configured. Add GOOGLE_CLIENT_ID and GOOGLE_CLIENT_SECRET to environment variables.",
    });
    return;
  }
  const state = crypto.randomBytes(16).toString("hex");
  registerOAuthState(state);
  const url = generateAuthUrl(state);
  res.json({ ok: true, url, state });
});

