// ── Server-side OAuth state store ─────────────────────────────────────────────
// States are generated by authenticated connect/start endpoints and consumed
// exactly once by the public callback. Each state expires after 10 minutes.

const OAUTH_STATE_TTL_MS = 10 * 60 * 1000;

const pendingOAuthStates = new Map<string, number>(); // state → expiry timestamp

function registerOAuthState(state: string): void {
  pendingOAuthStates.set(state, Date.now() + OAUTH_STATE_TTL_MS);
  // Prune expired states to prevent unbounded growth
  for (const [s, exp] of pendingOAuthStates) {
    if (Date.now() > exp) pendingOAuthStates.delete(s);
  }
}

function consumeOAuthState(state: string): boolean {
  const exp = pendingOAuthStates.get(state);
  if (exp === undefined) return false;
  pendingOAuthStates.delete(state);
  return Date.now() <= exp;
}

// ── Public router — OAuth callbacks only ──────────────────────────────────────
// These two routes must remain unauthenticated because Google redirects to them
// without our Bearer token. All other /google/* routes are protected below.

export const googlePublicRouter = Router();

googlePublicRouter.get("/google/callback", async (req: Request, res: Response) => {
  const { code, state, error: oauthError } = req.query as {
    code?: string;
    state?: string;
    error?: string;
  };

  if (oauthError) {
    res.redirect(`/?gbp_error=${encodeURIComponent(oauthError)}`);
    return;
  }
  if (!code) {
    res.status(400).json({ ok: false, error: "Missing OAuth code" });
    return;
  }

  // Validate that this state was generated by an authenticated session on this server
  if (!state || !consumeOAuthState(state)) {
    logger.warn("[GBP] OAuth callback rejected — invalid or expired state");
    res.status(400).json({ ok: false, error: "Invalid or expired OAuth state" });
    return;
  }

  try {
    const tokens = await getTokensFromCode(code);
    if (!tokens.access_token) throw new Error("No access token received");

    const userInfo = await fetch("https://www.googleapis.com/oauth2/v3/userinfo", {
      headers: { Authorization: `Bearer ${tokens.access_token}` },
    }).then(r => r.json()) as { sub?: string; email?: string };

    const client = await pool.connect();
    try {
      await client.query(
        `INSERT INTO google_accounts (id, org_id, google_id, email, access_token, refresh_token, token_expiry, scopes, connected_at)
         VALUES ($1,$2,$3,$4,$5,$6,$7,$8,now())
         ON CONFLICT (org_id) DO UPDATE SET
           google_id=$3, email=$4, access_token=$5,
           refresh_token=COALESCE($6, google_accounts.refresh_token),
           token_expiry=$7, scopes=$8, updated_at=now()`,
        [
          `ga_${ORG_ID}`,
          ORG_ID,
          userInfo.sub || "",
          userInfo.email || "",
          encryptToken(tokens.access_token),
          tokens.refresh_token ? encryptToken(tokens.refresh_token) : null,
          tokens.expiry_date ? new Date(tokens.expiry_date).toISOString() : null,
          JSON.stringify(tokens.scope?.split(" ") || []),
        ]
      );
    } finally {
      client.release();
    }

    store.logActivity({
      type: "team",
      label: `Google Business Profile connecté — ${userInfo.email || ""}`,
      targetType: "connector",
    });

    syncAll(ORG_ID).catch(e => logger.warn({ e }, "[GBP] Background sync failed"));

    const frontendUrl = process.env["FRONTEND_URL"] || "http://localhost:3000";
    res.redirect(`${frontendUrl}?gbp_connected=1`);
  } catch (e) {
    logger.error({ e }, "[GBP] OAuth callback failed");
    res.status(500).json({ ok: false, error: "OAuth exchange failed" });
  }
});

