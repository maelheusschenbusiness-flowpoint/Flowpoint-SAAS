router.get("/google/performance", async (req: Request, res: Response) => {
  const { locationId } = req.query as { locationId?: string };
  const accessToken = await getValidToken(ORG_ID);
  if (!accessToken) { res.status(401).json({ ok: false, error: "Google account not connected" }); return; }
  try {
    const client = await pool.connect();
    let locationName = locationId ?? "";
    if (!locationName) {
      const locs = await client.query(`SELECT raw_data FROM google_locations WHERE org_id=$1 LIMIT 1`, [ORG_ID]);
      client.release();
      if (locs.rows.length === 0) { res.json({ ok: true, metrics: [], summary: {} }); return; }
      const raw = locs.rows[0].raw_data as { name?: string };
      locationName = raw?.name ?? "";
    } else {
      client.release();
    }
    if (!locationName) { res.json({ ok: true, metrics: [], summary: {} }); return; }

    const metrics = await getPerformance(accessToken, locationName);

    const summary: Record<string, number> = {};
    for (const serie of metrics as Array<{ dailyMetric?: string; timeSeries?: { datedValues?: Array<{ value?: number }> } }>) {
      const key = serie.dailyMetric ?? "UNKNOWN";
      const total = (serie.timeSeries?.datedValues ?? []).reduce((s, v) => s + (v.value ?? 0), 0);
      summary[key] = total;
    }

    res.json({ ok: true, locationName, metrics, summary });
  } catch (e) {
    logger.error({ e }, "[GBP] performance route failed");
    res.status(500).json({ ok: false, error: "Failed to fetch performance data" });
  }
});

router.post("/google/post", async (req: Request, res: Response) => {
  const { locationId, text, callToActionType, callToActionUrl } = req.body as {
    locationId?: string; text?: string; callToActionType?: string; callToActionUrl?: string;
  };
  if (!text?.trim()) { res.status(400).json({ ok: false, error: "text is required" }); return; }

  const accessToken = await getValidToken(ORG_ID);
  if (!accessToken) { res.status(401).json({ ok: false, error: "Google account not connected" }); return; }

  let locationName = locationId ?? "";
  if (!locationName) {
    const client = await pool.connect();
    try {
      const locs = await client.query(`SELECT raw_data FROM google_locations WHERE org_id=$1 LIMIT 1`, [ORG_ID]);
      if (locs.rows.length > 0) {
        const raw = locs.rows[0].raw_data as { name?: string };
        locationName = raw?.name ?? "";
      }
    } finally { client.release(); }
  }
  if (!locationName) { res.status(400).json({ ok: false, error: "No location found. Sync GBP first." }); return; }

  const result = await publishGBPPost(accessToken, locationName, text, callToActionType, callToActionUrl);
  if (result.ok) {
    store.logActivity({ type: "ai", label: `Post GBP publié : "${text.slice(0, 60)}…"`, targetType: "google_business" });
  }
  res.json(result);
});

router.post("/google/reply", async (req: Request, res: Response) => {
  const { reviewId, locationId, comment, useAI } = req.body as {
    reviewId?: string; locationId?: string; comment?: string; useAI?: boolean;
  };
  if (!reviewId) { res.status(400).json({ ok: false, error: "reviewId is required" }); return; }

  const accessToken = await getValidToken(ORG_ID);
  if (!accessToken) { res.status(401).json({ ok: false, error: "Google account not connected" }); return; }

  const client = await pool.connect();
  let finalComment = comment ?? "";
  try {
    if (useAI || !finalComment) {
      const rev = await client.query(
        `SELECT reviewer_name, rating, comment FROM google_reviews WHERE review_id=$1 AND org_id=$2 LIMIT 1`,
        [reviewId, ORG_ID],
      );
      if (rev.rows.length > 0) {
        const row = rev.rows[0] as { reviewer_name: string; rating: number; comment: string };
        finalComment = await generateAIReply(row.reviewer_name, row.rating, row.comment);
      }
    }
    if (!finalComment) { res.status(400).json({ ok: false, error: "comment is required" }); return; }

    let locationName = locationId ?? "";
    if (!locationName) {
      const locs = await client.query(`SELECT raw_data FROM google_locations WHERE org_id=$1 LIMIT 1`, [ORG_ID]);
      if (locs.rows.length > 0) {
        const raw = locs.rows[0].raw_data as { name?: string };
        locationName = raw?.name ?? "";
      }
    }
    if (!locationName) { res.status(400).json({ ok: false, error: "No location found" }); return; }

    const result = await replyToReview(accessToken, locationName, reviewId, finalComment);

    if (result.ok) {
      await client.query(
        `UPDATE google_reviews SET reply_comment=$1, reply_updated_at=now() WHERE review_id=$2 AND org_id=$3`,
        [finalComment, reviewId, ORG_ID],
      );
      store.logActivity({ type: "team", label: `Réponse GBP publiée — avis ${reviewId}`, targetType: "google_business" });
    }
    res.json({ ok: result.ok, reply: finalComment, error: result.error });
  } finally {
    client.release();
  }
});

