import { describe, expect, it } from "vitest";
import { createCustomDomainCertPlan } from "./custom-domain-cert-preflight.js";

describe("custom-domain certification preflight", () => {
  it("requires a configurable externally controlled hostname", () => {
    expect(() => createCustomDomainCertPlan(undefined)).toThrow(/CUSTOM_DOMAIN_CERT_HOST/);
  });

  it("builds a side-effect-free plan for an external subdomain", () => {
    expect(createCustomDomainCertPlan(" Portal.External-Test.example. ")).toEqual({
      hostname: "portal.external-test.example",
      scope: "standard-external",
      ownershipTxt: {
        host: "_flowpoint-verify.portal.external-test.example",
        type: "TXT",
        value: "<generated by claim endpoint>",
      },
      authorization: "Standard custom-domain path; all reserved FlowPoint hostnames remain rejected.",
      stages: expect.arrayContaining([
        expect.stringContaining("TXT ownership"),
        expect.stringContaining("Render provisioning"),
        expect.stringContaining("cross-organization"),
        expect.stringContaining("Disable the server-side QA exception"),
        expect.stringContaining("cleanup operations"),
      ]),
      sideEffects: "none",
    });
  });

  it("describes the one QA exception without claiming to authorize it locally", () => {
    const plan = createCustomDomainCertPlan("Custom-Test.FlowPoint.Pro.");
    expect(plan).toMatchObject({
      hostname: "custom-test.flowpoint.pro",
      scope: "exact-internal-qa-exception",
      ownershipTxt: {
        host: "_flowpoint-verify.custom-test.flowpoint.pro",
        type: "TXT",
      },
      sideEffects: "none",
    });
    expect(plan.authorization).toMatch(/backend must confirm/i);
  });

  it.each(["portal.flowpoint.pro", "client.flowpoint.io", "flowpoint.pro", "www.example.net"])(
    "rejects reserved or unsupported hostname %s",
    (hostname) => {
      expect(() => createCustomDomainCertPlan(hostname)).toThrow();
    },
  );
});
