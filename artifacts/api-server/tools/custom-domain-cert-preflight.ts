import { pathToFileURL } from "node:url";
import {
  isCustomSubdomain,
  isExactQaCustomDomainCertificationHost,
  normalizeCustomDomain,
  QA_CUSTOM_DOMAIN_CERT_DOMAIN,
} from "../src/services/custom-domain-service.js";

export type CustomDomainCertPlan = {
  hostname: string;
  scope: "standard-external" | "exact-internal-qa-exception";
  ownershipTxt: { host: string; type: "TXT"; value: "<generated by claim endpoint>" };
  authorization: string;
  stages: string[];
  sideEffects: "none";
};

/**
 * Builds a non-mutating certification plan. This helper deliberately has no
 * database, DNS, Render, or HTTP client dependencies.
 */
export function createCustomDomainCertPlan(rawHostname: string | undefined): CustomDomainCertPlan {
  if (!rawHostname?.trim()) {
    throw new Error("Set CUSTOM_DOMAIN_CERT_HOST to the exact QA hostname or an external subdomain.");
  }

  const isQaExceptionCandidate = isExactQaCustomDomainCertificationHost(rawHostname);
  const hostname = isQaExceptionCandidate
    ? QA_CUSTOM_DOMAIN_CERT_DOMAIN
    : normalizeCustomDomain(rawHostname);
  if (!isCustomSubdomain(hostname)) {
    throw new Error("Certification requires a client subdomain; apex and www hostnames are not accepted.");
  }

  return {
    hostname,
    scope: isQaExceptionCandidate ? "exact-internal-qa-exception" : "standard-external",
    ownershipTxt: {
      host: `_flowpoint-verify.${hostname}`,
      type: "TXT",
      value: "<generated by claim endpoint>",
    },
    authorization: isQaExceptionCandidate
      ? "Candidate only: backend must confirm the fixed QA organization and live Render Test service; this preflight grants no exception."
      : "Standard custom-domain path; all reserved FlowPoint hostnames remain rejected.",
    stages: [
      isQaExceptionCandidate
        ? "Allow only custom-test.flowpoint.pro for the fixed internal QA organization and exact Render Test service."
        : "Confirm this hostname is on an external domain you control.",
      "Create the claim and publish only its generated TXT ownership record.",
      "Verify TXT ownership; Render provisioning must remain blocked until this succeeds.",
      "After separate user approval, verify Test Render DNS, HTTPS/TLS, and organization routing.",
      "Test cross-organization access is rejected before considering certification complete.",
      "Disable the server-side QA exception after certification.",
      "Present exact cleanup operations and wait for approval before deleting the test domain.",
    ],
    sideEffects: "none",
  };
}

function isCliInvocation(): boolean {
  return Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;
}

if (isCliInvocation()) {
  try {
    const plan = createCustomDomainCertPlan(process.env.CUSTOM_DOMAIN_CERT_HOST);
    console.log(JSON.stringify(plan, null, 2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : "Invalid custom-domain certification configuration.");
    process.exitCode = 1;
  }
}
